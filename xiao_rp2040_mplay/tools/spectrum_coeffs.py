#!/usr/bin/env python3
"""Generate fixed-point coefficients for a 16-band Chamberlin state-variable
filter bank, for the OLED spectrum analyzer.

Stdlib-only (just sin()), no venv/coloraide needed - unlike the color
gradient tool, run directly: `python3 spectrum_coeffs.py`.

Runs once, offline: sin() only ever happens here, on a desktop, computing
coefficients for a filter that then runs entirely in fixed-point on-device
(RP2040/Cortex-M0 has no FPU - see mod_player.c's own fixed-point mixer for
why float per-sample was a real problem there too). The SVF's f/q update
coefficients are constants once picked, so there is nothing left to
compute at runtime.

Usage:
    python3 spectrum_coeffs.py [--bands 16] [--fmin 80] [--fmax 8000]
                                [--fs 48000] [--q 5.0]
                                [--out ../src/spectrum_coeffs.h]
"""
import argparse
import math
from pathlib import Path

Q14 = 1 << 14  # coefficient fixed-point format, matches mod_player.c's
               # ALPHA_FRAC_BITS=14 filter-coefficient convention


def band_frequencies(n, fmin, fmax):
    ratio = fmax / fmin
    return [fmin * (ratio ** (i / (n - 1))) for i in range(n)]


def svf_coeffs(fc, fs, q):
    # Chamberlin state-variable filter: f = 2*sin(pi*fc/fs) is a small-angle
    # linear approximation, accurate well below Nyquist - fc maxing out at
    # fmax=8000 against fs=48000 (1/6 of Nyquist) is safely in that range.
    f = 2.0 * math.sin(math.pi * fc / fs)
    q_param = 1.0 / q
    return f, q_param


def to_q14(x):
    return round(x * Q14)


def emit_header(freqs, coeffs, out_path):
    lines = [
        "/* Generated by tools/spectrum_coeffs.py - do not edit by hand. */",
        "#ifndef SPECTRUM_COEFFS_H",
        "#define SPECTRUM_COEFFS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define SPECTRUM_BANDS {len(freqs)}",
        "",
        "/* Q0.14 fixed-point, same convention as mod_player.c's filter_alpha",
        " * (ALPHA_FRAC_BITS=14). Center frequencies in comments for reference",
        " * only - not needed at runtime, the f/q pair is everything the SVF",
        " * update needs.",
        " */",
    ]
    lines.append("static const int32_t spectrum_f_q14[SPECTRUM_BANDS] = {")
    for freq, (f, _q) in zip(freqs, coeffs):
        lines.append(f"\t{to_q14(f):6d},  /* {freq:7.1f} Hz */")
    lines.append("};")
    lines.append("")
    lines.append("static const int32_t spectrum_q_q14[SPECTRUM_BANDS] = {")
    for _freq, (_f, q) in zip(freqs, coeffs):
        lines.append(f"\t{to_q14(q):6d},")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    out_path.write_text("\n".join(lines) + "\n")
    print("wrote", out_path)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bands", type=int, default=16)
    ap.add_argument("--fmin", type=float, default=80.0)
    ap.add_argument("--fmax", type=float, default=8000.0)
    ap.add_argument("--fs", type=float, default=48000.0)
    ap.add_argument("--q", type=float, default=5.0)
    ap.add_argument("--out", type=Path, default=Path(__file__).parent / "../src/spectrum_coeffs.h")
    args = ap.parse_args()

    freqs = band_frequencies(args.bands, args.fmin, args.fmax)
    coeffs = [svf_coeffs(f, args.fs, args.q) for f in freqs]
    emit_header(freqs, coeffs, args.out)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate perceptually-uniform 3-stop colour gradient LUTs for the
NeoPixel VU meter, interpolated in OKLCH space via coloraide.

Naive RGB (or even HSV) interpolation from green to red passes through a
muddy, uneven-looking patch around the crossover - OKLCH interpolation
follows a smooth, perceptually even path through hue/chroma/lightness
instead, which is what actually looks like a clean gradient to the eye.

This runs once, offline, on a desktop - doing OKLCH math at runtime on a
Cortex-M0 (no FPU-friendly transcendentals, no reason to) would be wasted
work for something that's static data. The output header is committed;
re-run this only when a preset's stop points change.

Setup (one-time):
    uv venv .venv
    uv pip install --python .venv coloraide

Usage:
    .venv/bin/python3 color_gradient.py [--steps 64] [--out ../src/color_luts.h]
"""
import argparse
from pathlib import Path

from coloraide import Color

# name -> (stop0, stop1, stop2), each an (r, g, b) triple in 0..1 sRGB.
# Interpolated stop0 -> stop1 -> stop2 in OKLCH space. Values are full-
# fidelity/vivid - the runtime brightness cap (see vu_neopixel.c) scales
# the LUT's output down uniformly, so hue/relative-intensity ratios from
# the gradient are preserved rather than baked-in dim colours here.
PRESETS = {
    # Quiet -> loud VU meter: dark green -> yellow -> red.
    "vu_green_yellow_red": (
        (0.05, 0.25, 0.05),
        (0.60, 0.55, 0.05),
        (0.60, 0.05, 0.05),
    ),
    # "Rosewood Sky" - dark reddish-brown -> muted purple -> near-white
    # lavender, the user's own stop points.
    "blue_pink_white": (
        (0.15, 0.05, 0.07),
        (0.40, 0.30, 0.55),
        (0.92, 0.88, 0.98),
    ),
}


def build_lut(stops, steps):
    colors = [Color("srgb", list(s)) for s in stops]
    interp = Color.interpolate(colors, space="oklch")
    lut = []
    for i in range(steps):
        t = i / (steps - 1)
        c = interp(t).convert("srgb")
        c.fit("srgb", method="clip")
        lut.append(tuple(round(v * 255) for v in c[:-1]))
    return lut


def emit_header(luts, steps, out_path):
    lines = [
        "/* Generated by tools/color_gradient.py - do not edit by hand.",
        " * Re-run the script (see its docstring) if a preset's stop points change.",
        " */",
        "#ifndef COLOR_LUTS_H",
        "#define COLOR_LUTS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define COLOR_LUT_SIZE {steps}",
        "",
    ]
    for name, lut in luts.items():
        lines.append(f"static const uint8_t {name}_lut[COLOR_LUT_SIZE][3] = {{")
        for r, g, b in lut:
            lines.append(f"\t{{{r:3d}, {g:3d}, {b:3d}}},")
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    out_path.write_text("\n".join(lines) + "\n")
    print("wrote", out_path)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--steps", type=int, default=64)
    ap.add_argument("--out", type=Path, default=Path(__file__).parent / "../src/color_luts.h")
    args = ap.parse_args()

    luts = {name: build_lut(stops, args.steps) for name, stops in PRESETS.items()}
    emit_header(luts, args.steps, args.out)


if __name__ == "__main__":
    main()
